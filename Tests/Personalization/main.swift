import Foundation
let folder = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
defer { try? FileManager.default.removeItem(at: folder) }
let file = folder.appendingPathComponent("Personalization.json")
let snapshot = folder.appendingPathComponent("Backup/SIF-Personalization.json")
let png = Data([1, 2, 3]), replacement = Data([4, 5, 6])
var value = PersonalizationState(registry: ["legacy.example": "legacy-digest"])
precondition(!value.needsRecovery(host: "legacy.example", current: nil, displayCode: nil))
value.remember(host: "a.example", png: png, digest: "a", display: .fullTile)
value.remember(host: "b.example", png: replacement, digest: "b", display: nil)
precondition(!value.needsRecovery(host: "a.example", current: png, displayCode: 1))
precondition(value.needsRecovery(host: "a.example", current: png, displayCode: 0))
precondition(value.needsRecovery(host: "a.example", current: nil, displayCode: 1))
precondition(value.needsRecovery(host: "a.example", current: replacement, displayCode: 1))
precondition(!value.needsRecovery(host: "b.example", current: replacement, displayCode: 0))
try PersonalizationFile.write(value, to: file)
try PersonalizationFile.write(value, to: snapshot)
let before = try PersonalizationFile.read(file)
precondition(before == value)
value.forget("a.example")
precondition(value.registry["a.example"] == nil && value.icons["a.example"] == nil && value.icons["b.example"] != nil)
try PersonalizationFile.write(value, to: file)
let after = try PersonalizationFile.read(file)
precondition(value == after && before != after)
let restored = try PersonalizationFile.read(snapshot)
try PersonalizationFile.write(restored, to: file)
let result = try PersonalizationFile.read(file)
precondition(result == before)
let permissions = try FileManager.default.attributesOfItem(atPath: file.path)[.posixPermissions] as? Int
precondition(permissions == 0o600)
let link = folder.appendingPathComponent("link.json")
try FileManager.default.createSymbolicLink(at: link, withDestinationURL: file)
do { _ = try PersonalizationFile.read(link); fatalError("symlink accepted") } catch {}
do { try PersonalizationFile.write(value, to: link); fatalError("symlink overwritten") } catch {}
let intact = try PersonalizationFile.read(file)
precondition(intact == before)
let bad = folder.appendingPathComponent("bad.json")
try Data("invalid".utf8).write(to: bad)
do { _ = try PersonalizationFile.read(bad); fatalError("corrupt file accepted") } catch {}
print("OK: protection detection, migration model, isolated reset, atomic snapshot restore, permissions, symlinks, corrupt JSON")
